func writeTestPCM16WAV(t *testing.T, path string, seconds float64) {
	t.Helper()
	const rate, channels, bits = uint32(48000), uint16(2), uint16(16)
	dataSize := uint32(seconds * float64(rate) * float64(channels) * 2)
	var output bytes.Buffer
	output.WriteString("RIFF")
	_ = binary.Write(&output, binary.LittleEndian, uint32(36)+dataSize)
	output.WriteString("WAVEfmt ")
	_ = binary.Write(&output, binary.LittleEndian, uint32(16))
	_ = binary.Write(&output, binary.LittleEndian, uint16(1))
	_ = binary.Write(&output, binary.LittleEndian, channels)
	_ = binary.Write(&output, binary.LittleEndian, rate)
	_ = binary.Write(&output, binary.LittleEndian, rate*uint32(channels)*2)
	_ = binary.Write(&output, binary.LittleEndian, channels*2)
	_ = binary.Write(&output, binary.LittleEndian, bits)
	output.WriteString("data")
	_ = binary.Write(&output, binary.LittleEndian, dataSize)
	output.Write(make([]byte, int(dataSize)))
	if err := os.WriteFile(path, output.Bytes(), 0o644); err != nil {
		t.Fatal(err)
	}
}

