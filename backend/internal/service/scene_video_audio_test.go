func TestSceneReviewedAudioSelectionRequiresAcceptedCurrentMatchingCandidate(t *testing.T) {
	svc := newTestProjectService(t)
	db := svc.db
	if err := db.AutoMigrate(&models.Dialogue{}, &models.DialogueAudioCandidate{}, &models.SceneAudioCandidate{}); err != nil {
		t.Fatal(err)
	}
	project := models.Project{Title: "audio-scene"}
	if err := db.Create(&project).Error; err != nil {
		t.Fatal(err)
	}
	scene := models.Scene{ProjectID: project.ID, EpisodeN: 1, Generation: 1, Order: 1}
	if err := db.Create(&scene).Error; err != nil {
		t.Fatal(err)
	}
	dialogue := models.Dialogue{ProjectID: project.ID, SceneID: scene.ID, Order: 1, Character: "甲", SpeechType: "dialogue", Text: "原文", AudioFile: "take.flac", Status: "ready"}
	if err := db.Create(&dialogue).Error; err != nil {
		t.Fatal(err)
	}
	dialogue.AudioHash = svc.effectiveDialogueAudioHash(dialogue)
	if err := db.Model(&dialogue).Update("audio_hash", dialogue.AudioHash).Error; err != nil {
		t.Fatal(err)
	}
	if got := svc.sceneReviewedAudioSelection(&scene); got.Ready {
		t.Fatal("unreviewed audio became eligible")
	}
	candidate := models.DialogueAudioCandidate{ProjectID: project.ID, DialogueID: dialogue.ID, InputHash: dialogue.AudioHash, Provider: "test", File: "take.flac", Duration: 1, ReviewStatus: "accepted", IsCurrent: true}
	if err := db.Create(&candidate).Error; err != nil {
		t.Fatal(err)
	}
	got := svc.sceneReviewedAudioSelection(&scene)
	if !got.Ready || got.Candidate == nil || got.Candidate.ID != candidate.ID {
		t.Fatalf("selection=%+v", got)
	}
	files, err := svc.attachReviewedSceneAudio(&scene, nil)
	if err != nil {
		t.Fatal(err)
	}
	if files["dialogue_audio"][0].Name != "take.flac" {
		t.Fatalf("files=%+v", files)
	}
}

